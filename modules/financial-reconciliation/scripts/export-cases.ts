// Writes the reconciliation case corpus as plain JSON.
//
//   node scripts/export-cases.ts
//   node scripts/export-cases.ts --check
//
// This file is the deliverable for anyone implementing the contract in another
// language or against another stack: port the interpreter at the bottom of
// src/cases.ts and run this corpus against your own pipeline. The build fails
// if the exported file has drifted from the source, so the published
// specification cannot quietly stop describing the implementation.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CASES, MUTATIONS, T0 } from "../src/cases.ts";
import { CASE_STATES, EXCEPTION_REASONS } from "../src/types.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "reconciliation-cases.json");

const doc = {
  $comment:
    "Generated by scripts/export-cases.ts from src/cases.ts. Do not edit by hand.",
  version: 1,
  contract: "financial-reconciliation",
  epochMs: T0,
  caseStates: CASE_STATES,
  exceptionReasons: EXCEPTION_REASONS,
  gates: [
    "raw-store", "late-window", "statement-dedup", "engine", "ledger-entry-dedup",
  ],
  negativeControls: MUTATIONS,
  cases: CASES,
};
const rendered = JSON.stringify(doc, null, 2) + "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error("reconciliation-cases.json is missing; run: node scripts/export-cases.ts");
    process.exit(1);
  }
  if (current !== rendered) {
    console.error("reconciliation-cases.json is stale; run: node scripts/export-cases.ts");
    process.exit(1);
  }
  console.log(`corpus: up to date (${CASES.length} cases)`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, rendered);
  console.log(`wrote reconciliation-cases.json (${CASES.length} cases)`);
}
