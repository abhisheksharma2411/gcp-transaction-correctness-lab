import { writeFileSync } from "node:fs";
import { runScenario } from "../src/simulator.ts";
import { LOSE_LEADER, PARTITION_LEADER, SAFE, UNSAFE, scenario } from "../src/scenarios.ts";
import type { ScenarioResult } from "../src/types.ts";

const EXPERIMENTS: { id: string; question: string; build: (app: typeof SAFE) => ReturnType<typeof scenario> }[] = [
  {
    id: "E1-normal-cross-region",
    question: "A write from the non-leader region with everything healthy.",
    build: (app) => scenario("E1", app, { operations: [{ id: "n1", atMs: 1_000, region: "us-west" }] }),
  },
  {
    id: "E2-duplicate-across-regions",
    question: "The same operation id arrives in both regions. Two accepted writes?",
    build: (app) => scenario("E2", app, {
      operations: [
        { id: "d1", atMs: 1_000, region: "us-east" },
        { id: "d1", atMs: 2_000, region: "us-west" },
      ],
    }),
  },
  {
    id: "E3-leader-partitioned",
    question: "The leader region is isolated. A write lands in the minority side.",
    build: (app) => scenario("E3", app, {
      partition: PARTITION_LEADER,
      operations: [{ id: "p1", atMs: 25_000, region: "us-east" }],
    }),
  },
  {
    id: "E4-majority-side-during-partition",
    question: "Same partition, but the write lands in the majority side.",
    build: (app) => scenario("E4", app, {
      partition: PARTITION_LEADER,
      operations: [{ id: "m1", atMs: 35_000, region: "us-west" }],
    }),
  },
  {
    id: "E5-during-leader-election",
    question: "A write arrives inside the election window, before a new leader exists.",
    build: (app) => scenario("E5", app, {
      regionLoss: LOSE_LEADER,
      operations: [{ id: "e1", atMs: 22_000, region: "us-west" }],
    }),
  },
  {
    id: "E6-after-leader-election",
    question: "Same regional loss, after the election completes.",
    build: (app) => scenario("E6", app, {
      regionLoss: LOSE_LEADER,
      operations: [{ id: "e2", atMs: 35_000, region: "us-west" }],
    }),
  },
  {
    id: "E7-both-sides-same-operation",
    question: "One operation attempted on both sides of a partition at once.",
    build: (app) => scenario("E7", app, {
      partition: PARTITION_LEADER,
      operations: [
        { id: "b1", atMs: 25_000, region: "us-east" },
        { id: "b1", atMs: 25_500, region: "us-west" },
      ],
    }),
  },
  {
    id: "E8-drain-and-restore",
    question: "Traffic drains to the surviving region and comes back after recovery.",
    build: (app) => scenario("E8", app, {
      regionLoss: LOSE_LEADER,
      operations: [
        { id: "r1", atMs: 10_000, region: "us-east" },
        { id: "r2", atMs: 25_000, region: "us-west" },
        { id: "r3", atMs: 35_000, region: "us-west" },
        { id: "r4", atMs: 50_000, region: "us-east" },
      ],
    }),
  },
];

const rows: string[] = [];
const all: Record<string, unknown> = {};

rows.push("# Regional authority results\n");
rows.push("Generated by `make report`. Deterministic.\n");
rows.push("All figures are **simulated results** from a model implementing the documented");
rows.push("majority-quorum rule. This is not a reimplementation of Spanner.\n");
rows.push("`doubleCommits` must be 0 in every row, under both policies. `unbacked` is the");
rows.push("application-layer split brain, and it is the column that separates them.\n");
rows.push("| Experiment | App policy | Decisions | doubleCommits | unbacked (hindsight) | unconfirmed (at decision time) | safeMode |");
rows.push("|---|---|---|---:|---:|---:|---:|");

const summarise = (r: ScenarioResult) =>
  r.decisions.map((d) => `${d.decidedIn}=${d.outcome}`).join(", ");

for (const exp of EXPERIMENTS) {
  const safe = runScenario(exp.build(SAFE));
  const unsafe = runScenario(exp.build(UNSAFE));
  all[exp.id] = { question: exp.question, safe, unsafe };
  for (const [name, r] of [["authority-only", safe], ["local-state", unsafe]] as const) {
    rows.push(
      `| ${exp.id} | ${name} | ${summarise(r)} | ${r.doubleCommits.length} |` +
        ` ${r.unbackedFulfilments.length} | ${r.unconfirmedFulfilments} | ${r.safeModeCount} |`,
    );
  }
  writeFileSync(`results/${exp.id}.json`, JSON.stringify({ question: exp.question, safe, unsafe }, null, 2));
}

writeFileSync("results/experiments.json", JSON.stringify(all, null, 2));
writeFileSync("results/experiments.md", rows.join("\n") + "\n");
console.log(rows.join("\n"));
