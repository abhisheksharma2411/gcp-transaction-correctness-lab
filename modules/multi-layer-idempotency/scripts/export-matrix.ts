// Writes the conformance matrix as plain JSON.
//
//   node scripts/export-matrix.ts
//   node scripts/export-matrix.ts --check
//
// This file is the deliverable for anyone implementing the contract in another
// language: port the ~120-line interpreter in src/conformance.ts and run this
// matrix against your own implementation. If it passes, your implementation
// satisfies the same contract as this one.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { MATRIX } from "../src/conformance.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "conformance-matrix.json");

const doc = {
  $comment:
    "Generated by scripts/export-matrix.ts from src/conformance.ts. Do not edit by hand.",
  version: 1,
  contract: "multi-layer-idempotency",
  decisions: ["FIRST", "IN_PROGRESS", "REPLAY", "CONFLICT", "EXPIRED"],
  layers: ["contract", "business-uniqueness", "provider", "effect-ledger"],
  cases: MATRIX,
};
const rendered = JSON.stringify(doc, null, 2) + "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error("conformance-matrix.json is missing; run: node scripts/export-matrix.ts");
    process.exit(1);
  }
  if (current !== rendered) {
    console.error("conformance-matrix.json is stale; run: node scripts/export-matrix.ts");
    process.exit(1);
  }
  console.log(`matrix: up to date (${MATRIX.length} cases)`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, rendered);
  console.log(`wrote conformance-matrix.json (${MATRIX.length} cases)`);
}
