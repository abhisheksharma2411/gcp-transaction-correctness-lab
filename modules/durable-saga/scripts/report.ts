// Runs every scenario, the whole failure matrix and every negative control,
// then writes results/ deterministically.
//
//   node scripts/report.ts
//
// No cloud project, no credentials, no network. Re-running produces
// byte-identical output: nothing here reads a clock.

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SAGA_V1, SAGA_V2, pivotIndex, verifyDefinition } from "../src/saga.ts";
import { mutateDefinition } from "../src/mutate.ts";
import { SPEC_MUTATIONS } from "../src/policy.ts";
import { SCENARIOS } from "../src/scenarios.ts";
import { INJECTIONS, INJECTION_MEANING, failureMatrix, tally, timeline } from "../src/matrix.ts";
import { allControls, render } from "../src/controls.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, "..", "results");
mkdirSync(RESULTS, { recursive: true });

// --- E1: the definition, checked before anything runs -----------------------

const checksV1 = verifyDefinition(SAGA_V1);
const checksV2 = verifyDefinition(SAGA_V2);

const specControls = SPEC_MUTATIONS.map((m) => {
  const findings = verifyDefinition(mutateDefinition(m));
  const failed = findings.filter((f) => !f.ok).map((f) => f.check);
  return { mutation: m, failed, caught: failed.length > 0 };
});

// --- E2: the named scenarios ------------------------------------------------

const scenarios = SCENARIOS.map((s) => {
  const r = s.run();
  return {
    id: s.id, title: s.title, covers: s.covers,
    finalState: r.record.state,
    verdict: r.audit.verdict,
    agreed: r.disagreement === null,
    disagreement: r.disagreement,
    restarts: r.restarts,
    effects: r.world.allRecords().filter((x) => x.kind === "applied").length,
    compensations: r.world.allRecords().filter((x) => x.kind === "compensated").length,
    refusals: [...new Set(r.refusals.map((x) => x.code))].sort(),
    historyLength: r.record.history.length,
  };
});

// --- E3: the failure matrix -------------------------------------------------

const matrix = failureMatrix();
const counts = tally(matrix);
const disagreements = matrix.filter((r) => !r.agreed);
const duplicates = matrix.reduce((n, r) => n + r.duplicateEffects, 0);

// --- E4: the negative controls ----------------------------------------------

const controls = allControls();

// --- E5: one complete timeline ----------------------------------------------

const s7 = SCENARIOS.find((s) => s.id === "S7")!.run();
const s7Timeline = timeline(s7.record);

// --- write ------------------------------------------------------------------

const report = {
  module: "durable-saga",
  label: "Simulated result",
  definition: {
    version1: { steps: SAGA_V1.steps.length, pivot: SAGA_V1.steps[pivotIndex(SAGA_V1)]!.name, checks: checksV1 },
    version2: { steps: SAGA_V2.steps.length, pivot: SAGA_V2.steps[pivotIndex(SAGA_V2)]!.name, checks: checksV2 },
    specControls,
  },
  scenarios,
  matrix: {
    rows: matrix.length,
    injections: INJECTIONS,
    outcomes: counts,
    disagreements: disagreements.length,
    duplicateEffects: duplicates,
    detail: matrix,
  },
  controls: controls.map((c) => ({
    mutation: c.mutation, intent: c.intent, probe: c.probe, expected: c.expected,
    baseline: render(c.baseline), mutated: render(c.mutated), changed: c.changed,
  })),
};

writeFileSync(join(RESULTS, "report.json"), JSON.stringify(report, null, 2) + "\n");

const md: string[] = [];
md.push("# durable-saga — results");
md.push("");
md.push("**Simulated result.** Generated by `make report` from the module in this");
md.push("directory. No cloud project, no credentials, no network. Re-running the");
md.push("command reproduces this file byte for byte.");
md.push("");
md.push("## 1. The definition, checked before anything runs");
md.push("");
md.push("| check | version 1 | version 2 |");
md.push("|---|---|---|");
checksV1.forEach((f, i) => {
  md.push(`| \`${f.check}\` | ${f.ok ? "PASS" : "**FAIL**"} | ${checksV2[i]!.ok ? "PASS" : "**FAIL**"} |`);
});
md.push("");
md.push("Each check is then run against a definition deliberately broken in the way");
md.push("it claims to catch.");
md.push("");
md.push("| broken definition | checks that went red |");
md.push("|---|---|");
for (const c of specControls) {
  md.push(`| \`${c.mutation}\` | ${c.failed.map((x) => `\`${x}\``).join(", ") || "**none — the check is not working**"} |`);
}
md.push("");
md.push("## 2. Scenarios");
md.push("");
md.push("| id | scenario | final state | ledgers say | agree | effects | compensations | restarts |");
md.push("|---|---|---|---|---|---:|---:|---:|");
for (const s of scenarios) {
  md.push(`| ${s.id} | ${s.title} | \`${s.finalState}\` | ${s.verdict} | ${s.agreed ? "yes" : "**no**"} | ${s.effects} | ${s.compensations} | ${s.restarts} |`);
}
md.push("");
md.push("## 3. The failure matrix");
md.push("");
md.push(`${matrix.length} runs. One fault at one point of one step, then the saga is driven`);
md.push("to quiescence and scored twice: by its own record, and by an auditor that reads");
md.push("only the five participants' effect ledgers.");
md.push("");
md.push("| injection | meaning |");
md.push("|---|---|");
for (const i of INJECTIONS) md.push(`| \`${i}\` | ${INJECTION_MEANING[i]} |`);
md.push("");
md.push("| outcome | runs |");
md.push("|---|---:|");
for (const k of Object.keys(counts) as (keyof typeof counts)[]) md.push(`| ${k} | ${counts[k]} |`);
md.push(`| **disagreements between the saga and the ledgers** | **${disagreements.length}** |`);
md.push(`| **duplicate protected effects** | **${duplicates}** |`);
md.push("");
md.push("The full table is in `matrix.md`.");
md.push("");
md.push("## 4. Negative controls");
md.push("");
md.push("Each mechanism is removed in turn, and a named observable has to change.");
md.push("");
md.push("| mutation | probe | observable that changed |");
md.push("|---|---|---|");
for (const c of controls) {
  md.push(`| \`${c.mutation}\` | ${c.probe} | ${c.changed ? c.expected : "**nothing — this control is not working**"} |`);
}
md.push("");
md.push("| mutation | unmutated run | mutated run |");
md.push("|---|---|---|");
for (const c of controls) {
  md.push(`| \`${c.mutation}\` | ${render(c.baseline)} | ${render(c.mutated)} |`);
}
md.push("");
md.push("Read as `state / ledger verdict / agreement / ledger violations / refusals / applied effects`.");
md.push("");
writeFileSync(join(RESULTS, "report.md"), md.join("\n"));

const mm: string[] = [];
mm.push("# Failure matrix");
mm.push("");
mm.push("**Simulated result.** Generated by `make report`.");
mm.push("");
mm.push("`outcome` is the saga's own account of itself. `ledgers` is what an auditor");
mm.push("that never ran the saga concludes from the participants' effect records. The");
mm.push("last column is the one that matters.");
mm.push("");
mm.push("| direction | step | injection | final state | outcome | ledgers | live effects | restarts | agree |");
mm.push("|---|---|---|---|---|---|---|---:|---|");
for (const r of matrix) {
  mm.push(`| ${r.direction} | \`${r.step}\` | \`${r.injection}\` | \`${r.finalState}\` | ${r.outcome} | ${r.verdict} | ${r.liveEffects.length === 0 ? "—" : r.liveEffects.map((x) => `\`${x}\``).join(" ")} | ${r.restarts} | ${r.agreed ? "yes" : `**no** — ${r.disagreement}`} |`);
}
mm.push("");
writeFileSync(join(RESULTS, "matrix.md"), mm.join("\n"));

const tl: string[] = [];
tl.push("# One saga's timeline");
tl.push("");
tl.push("**Simulated result.** Generated by `make report`. Scenario S7: the pivot is");
tl.push("refused, the compensation chain runs, one compensation exhausts its attempts,");
tl.push("an operator resumes it, and the chain finishes.");
tl.push("");
tl.push("```text");
tl.push("seq | time     | event | step | reason code | detail");
for (const l of s7Timeline) tl.push(l);
tl.push("```");
tl.push("");
writeFileSync(join(RESULTS, "timeline.md"), tl.join("\n"));

console.log(`wrote results/report.json, report.md, matrix.md, timeline.md`);
console.log(`matrix: ${matrix.length} runs, ${disagreements.length} disagreements, ${duplicates} duplicate effects`);
