// Runs every scenario and writes results/ deterministically.
//
//   node scripts/report.ts
//
// No cloud project, no credentials, no network. Re-running produces
// byte-identical output: there is no Date.now() anywhere in src/, and every
// function that needs the time takes it as an argument.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { CONTROLS, runControls, standardRun } from "../src/controls.ts";
import { projectionFingerprint, rebuildProjection } from "../src/projection.ts";
import { CRASH_POINTS, STRATEGIES, TOPIC, crashWindow } from "../src/scenarios.ts";
import type { CaptureStrategy } from "../src/source.ts";
import type { CrashPoint } from "../src/types.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, "..", "results");
mkdirSync(RESULTS, { recursive: true });

// --- E1: the crash-window matrix -------------------------------------------
//
// The same crash, at the same point, under each capture strategy. This is the
// experiment the article's comparison rests on.

/** A checkpoint only exists where a relay does. */
function applicable(strategy: CaptureStrategy, crashAt: CrashPoint): boolean {
  if (crashAt !== "after-publish-before-checkpoint") return true;
  return strategy === "outbox";
}

const crashMatrix = CRASH_POINTS.flatMap((crashAt) =>
  STRATEGIES.filter((s) => applicable(s, crashAt)).map((strategy) => {
    const r = crashWindow(strategy, crashAt);
    return {
      crashAt,
      strategy,
      committed: r.committed,
      eventsOnTopic: r.eventsOnTopic,
      protectedEffects: r.protectedEffects,
      findings: [...new Set(r.findings)].sort(),
    };
  }),
);

// --- E2: the standard run ---------------------------------------------------

const run = standardRun();
const trace = run.world.trace;
const tally = {
  committedChanges: trace.count("commit"),
  eventsCaptured: run.world.source.eventLog().length,
  messagesOnTopic: run.world.broker.publishedMessages(TOPIC).length,
  deliveries: trace.count("deliver"),
  effectApplications: run.effectApplications,
  distinctProtectedEffects: run.protectedEffects,
  suppressedByInbox: run.world.inventory.suppressedByInbox + run.world.notifications.suppressedByInbox,
  suppressedBySequence: trace.count("stale"),
  suppressedByEffectLedger:
    run.world.inventory.suppressedByEffectLedger + run.world.notifications.suppressedByEffectLedger,
  deadLettered: trace.count("dead-letter"),
  repaired: trace.count("dead-letter-repair"),
  replayed: trace.count("replay-publish"),
};

// --- E3: negative controls --------------------------------------------------

const controls = runControls();

// --- E4: projection rebuild -------------------------------------------------

const log = run.world.source.eventLog();
const projection = {
  forward: projectionFingerprint(rebuildProjection(log)),
  reversed: projectionFingerprint(rebuildProjection([...log].reverse())),
};

// --- write ------------------------------------------------------------------

const payload = {
  generatedFrom: "scripts/report.ts",
  note: "Deterministic. No cloud project, no credentials, no network.",
  crashMatrix,
  standardRun: { tally, findings: run.detail },
  negativeControls: controls,
  projection,
};
writeFileSync(join(RESULTS, "lineage.json"), JSON.stringify(payload, null, 2) + "\n");

const L: string[] = [];
L.push("# outbox-inbox-replay results");
L.push("");
L.push("Generated by `scripts/report.ts`. Deterministic: no cloud project, no");
L.push("credentials, no network.");
L.push("");
L.push("## One crash, three ways of capturing the event");
L.push("");
L.push("One order is confirmed. The process dies at the point named in the first");
L.push("column. Everything that can recover then recovers, and the lineage");
L.push("verifier is run over what is left.");
L.push("");
L.push("| crash point | capture strategy | committed | events on topic | protected effects | findings |");
L.push("|---|---|---:|---:|---:|---|");
for (const row of crashMatrix) {
  L.push(
    `| ${row.crashAt} | \`${row.strategy}\` | ${row.committed} | ${row.eventsOnTopic} | ` +
      `${row.protectedEffects} | ${row.findings.join(", ") || "none"} |`,
  );
}
L.push("");
L.push("`publish-after-commit` loses the event. `publish-before-commit` keeps an");
L.push("event describing a change that never happened. The outbox turns both into");
L.push("a duplicate publication, which the consumer absorbs.");
L.push("");
L.push("## The standard run, counted");
L.push("");
L.push("Five orders, one of them changed twice. One poison event. One event at a");
L.push("schema version the consumers do not know. A relay that dies mid-batch. A");
L.push("replay of one aggregate's history afterwards.");
L.push("");
L.push("| measured | count |");
L.push("|---|---:|");
for (const [k, v] of Object.entries(tally)) {
  L.push(`| ${k.replace(/([A-Z])/g, " $1").toLowerCase()} | ${v} |`);
}
L.push("");
L.push(`Lineage findings: **${run.detail.length}**.`);
L.push("");
L.push("## Negative controls");
L.push("");
L.push("Every finding code has to be provoked by a named defect, and each control");
L.push("must produce its stated codes and no others. A control blunt enough to");
L.push("redden several unrelated checks is rejected, because \"I broke it and the");
L.push("checker complained\" is not evidence that any particular check works.");
L.push("");
L.push("| control | defect | expected | produced | verdict |");
L.push("|---|---|---|---|---|");
for (const c of controls) {
  const verdict = c.mustBeRejected
    ? c.blunt
      ? "rejected as blunt, as intended"
      : "**not blunt enough to be a useful control of bluntness**"
    : c.detected && !c.blunt
      ? "detected"
      : "**missed**";
  L.push(
    `| \`${c.name}\` | ${c.defect} | ${c.expected.join(", ") || "—"} | ` +
      `${c.produced.join(", ") || "—"} | ${verdict} |`,
  );
}
L.push("");
const covered = new Set(CONTROLS.flatMap((c) => c.expect));
L.push(`${covered.size} of 10 finding codes are provoked by a control.`);
L.push("");
L.push("## Projection rebuild");
L.push("");
L.push("The read model is rebuilt from the event log twice: once in order, once");
L.push("from the reversed log. A projection that depends on the order the events");
L.push("are read in is not a projection of the events.");
L.push("");
L.push("```");
L.push(`forward:  ${projection.forward}`);
L.push(`reversed: ${projection.reversed}`);
L.push(`identical: ${projection.forward === projection.reversed}`);
L.push("```");
L.push("");
writeFileSync(join(RESULTS, "report.md"), L.join("\n"));

// A readable slice of the audit trail, for the article's lineage figure.
const traceLines = trace.lines();
writeFileSync(join(RESULTS, "trace.txt"), traceLines.join("\n") + "\n");

console.log(
  `wrote results/report.md, results/lineage.json and results/trace.txt ` +
    `(${traceLines.length} trace entries, ${run.detail.length} findings)`,
);
