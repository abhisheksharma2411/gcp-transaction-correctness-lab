// Regenerate every number the article quotes.
//
//   node scripts/report.ts
//
// Deterministic: no cloud project, no credentials, no network, no clock. Run
// it twice and the bytes are identical.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEADLINE_FIXTURES, MANITOBA_CASE, at, evidence } from '../src/scenarios.ts';
import { computeDeadline, minutesRemaining, ruleSetByVersion, statusAt } from '../src/deadline.ts';
import { render, fromCivil, zoneTableByVersion, offsetAt } from '../src/zones.ts';
import { horizonTable, reproduceAll, runPopulation, allAdjustments } from '../src/run.ts';
import { timeline, stateAt } from '../src/case.ts';
import { MAX_SCHEDULE_HORIZON_MS } from '../src/timers.ts';
import { diffPackets, reproduce } from '../src/manifest.ts';
import { create as retain, placeHold, releaseHold, retainUntil, tryDelete } from '../src/retention.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, '..', 'results');

const out: string[] = [];
const w = (line = '') => out.push(line);

w('# dispute-deadline-workflow results');
w();
w('Generated by `scripts/report.ts`. Deterministic: no cloud project, no');
w('credentials, no network, and no reading of the clock. `Simulated result`.');
w();

// ---------------------------------------------------------------------------
const run = runPopulation();
const adjustments = allAdjustments(run);

w('## Seven cases, one number that never moves');
w();
w('A population of seven synthetic disputes, run from notification to outcome.');
w();
w('| measured | count |');
w('|---|---:|');
w(`| cases opened | ${run.tally.casesOpened} |`);
w(`| duplicate notifications suppressed | ${run.tally.duplicateNotificationsSuppressed} |`);
w(`| packets approved | ${run.tally.packetsApproved} |`);
w(`| submissions accepted inside the deadline | ${run.tally.submissionsAccepted} |`);
w(`| submissions accepted **past** the deadline | ${run.tally.submissionsAcceptedPastDue} |`);
w(`| submissions with an unknown outcome | ${run.tally.submissionsUnknown} |`);
w(`| cases that expired with no answer | ${run.tally.casesExpiredUnanswered} |`);
w(`| cases the provider permitted no answer to | ${run.tally.casesNoResponsePermitted} |`);
w(`| **errors the system raised** | **${run.tally.errorsRaised}** |`);
w(`| money lost, minor units | ${run.tally.moneyLostMinor} |`);
w(`| money recovered, minor units | ${run.tally.moneyRecoveredMinor} |`);
w();
w('The last three rows are the point. One case expired without an answer, one');
w('was submitted after its deadline and accepted anyway, and one was never');
w('answerable -- and the running system raised a single error between them, for');
w('a duplicate submission that the provider refused. A dashboard counting');
w('exceptions would have shown one incident and no losses.');
w();
for (const note of run.notes) w(`- ${note}`);
w();

// ---------------------------------------------------------------------------
w('## Deadline fixtures');
w();
w('Each row is one notification put through the engine. `basis` records where');
w('the deadline came from, and nothing else in the system is allowed to');
w('recompute it.');
w();
w('| id | what | basis | rules | zone table | deadline (UTC) | internal target (UTC) |');
w('|---|---|---|---|---|---|---|');
const decisions = DEADLINE_FIXTURES.map((f) => ({
  fixture: f,
  decision: computeDeadline({
    notification: f.notification,
    rules: ruleSetByVersion(f.ruleVersion),
    zoneTableVersion: f.zoneTableVersion,
  }),
}));
for (const { fixture, decision } of decisions) {
  w(
    `| **${fixture.id}** | ${fixture.what} | ${decision.basis} | ${decision.ruleVersion} | ${decision.zoneTableVersion} | ${render(decision.deadline)} | ${render(decision.internalTarget)} |`,
  );
}
w();

const d04 = decisions.find((x) => x.fixture.id === 'D04')!.decision;
const d05 = decisions.find((x) => x.fixture.id === 'D05')!.decision;
const d06 = decisions.find((x) => x.fixture.id === 'D06')!.decision;
const d07 = decisions.find((x) => x.fixture.id === 'D07')!.decision;

w('### The same local cutoff, two different instants');
w();
w('D04 and D05 both end at 17:00 in New York. D04 falls while daylight saving');
w('is in force and D05 after it ends, so the deadline moves by');
w(`${(((d05.deadline! % 86_400_000) - (d04.deadline! % 86_400_000)) / 3_600_000).toFixed(0)} hour in UTC while the contract's text does not change at all.`);
w();
w(`- D04 cutoff resolves to **${render(d04.deadline)}**`);
w(`- D05 cutoff resolves to **${render(d05.deadline)}**`);
w();

w('### The same input, two different answers');
w();
w('D06 and D07 are the identical notification under the identical rule set. The');
w('only difference is which version of the zone table was in force.');
w();
w('| | zone table | deadline (UTC) |');
w('|---|---|---|');
w(`| D06 | ${d06.zoneTableVersion} | ${render(d06.deadline)} |`);
w(`| D07 | ${d07.zoneTableVersion} | ${render(d07.deadline)} |`);
w();
w(`Difference: **${Math.round((d06.deadline! - d07.deadline!) / 60_000)} minutes**, from a rule change published five weeks`);
w('before the case was opened. A deadline that does not record which table');
w('produced it cannot be re-derived once the host is updated.');
w();

// Manitoba civil resolution under both tables.
const mbPrev = fromCivil(zoneTableByVersion('synthetic-2026d'), MANITOBA_CASE.zone, MANITOBA_CASE.civil);
const mbCurr = fromCivil(zoneTableByVersion('synthetic-2026e'), MANITOBA_CASE.zone, MANITOBA_CASE.civil);
w('The same civil time resolved directly:');
w();
w('| table | offset in force | instant |');
w('|---|---:|---|');
w(`| synthetic-2026d | ${offsetAt(zoneTableByVersion('synthetic-2026d'), MANITOBA_CASE.zone, mbPrev.instant)} min | ${render(mbPrev.instant)} |`);
w(`| synthetic-2026e | ${offsetAt(zoneTableByVersion('synthetic-2026e'), MANITOBA_CASE.zone, mbCurr.instant)} min | ${render(mbCurr.instant)} |`);
w();

// ---------------------------------------------------------------------------
w('## Civil times that are not one instant');
w();
w('A wall-clock time is not always a moment. The resolution policy is to take');
w('the earliest candidate in every ambiguous case, because for a deadline the');
w('earlier reading is the safe one.');
w();
w('| zone | civil time | ambiguity | candidates | chosen |');
w('|---|---|---|---:|---|');
const ambiguityCases = [
  { zone: 'America/New_York', civil: { year: 2026, month: 11, day: 1, minutes: 60 + 30 }, label: '2026-11-01 01:30' },
  { zone: 'America/New_York', civil: { year: 2026, month: 3, day: 8, minutes: 120 + 30 }, label: '2026-03-08 02:30' },
  { zone: 'America/New_York', civil: { year: 2026, month: 11, day: 1, minutes: 17 * 60 }, label: '2026-11-01 17:00' },
  { zone: 'Australia/Lord_Howe', civil: { year: 2026, month: 10, day: 4, minutes: 120 + 15 }, label: '2026-10-04 02:15' },
];
const table2026e = zoneTableByVersion('synthetic-2026e');
for (const item of ambiguityCases) {
  const resolved = fromCivil(table2026e, item.zone, item.civil);
  w(
    `| ${item.zone} | ${item.label} | ${resolved.ambiguity} | ${resolved.candidates.length} | ${render(resolved.instant)} |`,
  );
}
w();
w('Lord Howe Island is in the table because its daylight shift is thirty');
w('minutes, not sixty. Code that normalises an ambiguity by adding or');
w('subtracting an hour is wrong there, and wrong without saying so.');
w();

// ---------------------------------------------------------------------------
w('## The scheduling horizon');
w();
w(
  `Cloud Tasks publishes a maximum schedule time of 30 days. That is ${MAX_SCHEDULE_HORIZON_MS} ms,`,
);
w('and it is a system limit rather than a quota, so it is not negotiable. Any');
w('target further out needs a chain of renewals, and each hop is an independent');
w('opportunity for the chain to break without anything being logged.');
w();
w('| case | days to internal target | renewal hops needed |');
w('|---|---:|---:|');
for (const row of horizonTable(run, at('2026-10-07T00:00:00Z'))) {
  w(`| ${row.caseId} | ${row.daysOut < 0 ? 'n/a' : row.daysOut} | ${row.hops} |`);
}
w();
w('The sweep, run over the same rows as they stood on 2026-10-26:');
w();
w('| measured | value |');
w('|---|---:|');
w(`| non-terminal cases scanned | ${run.sweepAt.scanned} |`);
w(`| already answered | ${run.sweepAt.answered} |`);
w(`| due, deadline not yet passed | ${run.sweepAt.due.length} |`);
w(`| past deadline, unanswered | ${run.sweepAt.pastDeadline.length} |`);
w(`| open with no deadline | ${run.sweepAt.noDeadline.length} |`);
w();
w(`Due: ${run.sweepAt.due.join(', ') || '(none)'}.`);
w();

// ---------------------------------------------------------------------------
w('## Packet reproduction');
w();
const repro = reproduceAll(run);
w(`Every packet re-derived from its own entries: **${repro.matched} of ${repro.total}** match the stored manifest hash.`);
w();
w('| packet | version | items | manifest hash | approved by |');
w('|---|---:|---:|---|---|');
for (const kase of run.cases) {
  for (const packet of kase.packets) {
    w(
      `| ${packet.packetId} | ${packet.version} | ${packet.entries.length} | \`${packet.manifestHash.slice(0, 16)}\` | ${packet.approvedBy} |`,
    );
  }
}
w();
const twoVersion = run.cases.find((c) => c.packets.length > 1);
if (twoVersion) {
  const [first, second] = twoVersion.packets;
  w(`What changed between ${first!.packetId} v${first!.version} and v${second!.version}:`);
  w();
  for (const line of diffPackets(first!, second!)) w(`- ${line}`);
  w();
  w('The first packet is still there, still reproducible, and still carries the');
  w('name of the person who approved it. That matters because it may already');
  w('have been sent.');
  w();
}

// A packet whose stored hash has been tampered with.
const sample = run.cases.find((c) => c.packets.length > 0)!.packets[0]!;
const tampered = { ...sample, manifestHash: sample.manifestHash.replace(/^./, '0') };
w(`Reproduction of a packet whose stored hash has been altered by one character: **${reproduce(tampered).ok ? 'MATCH' : 'MISMATCH'}**.`);
w();

// ---------------------------------------------------------------------------
w('## One case, end to end');
w();
const worked = run.cases.find((c) => c.providerCaseId === 'dp-2002')!;
w(`\`${worked.caseId}\` -- opened ${render(worked.openedAt)}, deadline ${render(worked.decision.deadline)}, final state \`${worked.state}\`.`);
w();
w('```text');
for (const line of timeline(worked)) w(line);
w('```');
w();
w('State recovered by replaying that trail, rather than read from the current row:');
w();
w('| instant | state |');
w('|---|---|');
for (const instant of ['2026-10-05T12:00:00Z', '2026-10-09T13:00:00Z', '2026-10-10T08:30:00Z', '2026-10-11T00:00:00Z', '2026-12-01T00:00:00Z']) {
  w(`| ${instant} | ${stateAt(worked, at(instant))} |`);
}
w();

// ---------------------------------------------------------------------------
w('## Adjustment events');
w();
w('Events, not postings. The ledger decides what to post; this module states');
w('what happened and when.');
w();
w('| case | kind | amount (minor) | occurred | basis |');
w('|---|---|---:|---|---|');
for (const event of adjustments) {
  w(`| ${event.caseId} | ${event.kind} | ${event.amountMinor} | ${render(event.occurredAt)} | ${event.basis} |`);
}
w();

// ---------------------------------------------------------------------------
w('## Access decisions');
w();
w('| actor | role | item | purpose | allowed | reason |');
w('|---|---|---|---|---|---|');
for (const entry of run.accessLog) {
  w(
    `| ${entry.actorId} | ${entry.role} | ${entry.itemId} | ${entry.purpose} | ${entry.allowed ? 'yes' : 'no'} | ${entry.reason} |`,
  );
}
w();
w('Data Access audit logs are off by default outside BigQuery, and the default');
w('log bucket keeps 30 days. A dispute whose retention obligation is years long');
w('therefore has to keep its own record of who read the evidence, which is what');
w('this table is.');
w();

// ---------------------------------------------------------------------------
w('## Holds and retention');
w();
const stored = retain('evidence-1', at('2026-10-06T10:00:00Z'), 365 * 86_400_000, []);
const withEvent = placeHold(stored, 'EVENT_BASED');
const withTemp = placeHold(stored, 'TEMPORARY');
const releasedEvent = releaseHold(withEvent, 'EVENT_BASED', at('2027-06-01T00:00:00Z'));
const releasedTemp = releaseHold(withTemp, 'TEMPORARY', at('2027-06-01T00:00:00Z'));
w('| object | hold | retain until before release | retain until after release |');
w('|---|---|---|---|');
w(`| evidence-1 | event-based | ${render(retainUntil(withEvent))} | ${render(retainUntil(releasedEvent.object))} |`);
w(`| evidence-1 | temporary | ${render(retainUntil(withTemp))} | ${render(retainUntil(releasedTemp.object))} |`);
w();
w('Releasing the event-based hold restarted the retention clock and pushed the');
w('earliest deletion date out by eight months. Releasing the temporary hold did');
w('not. Choosing the wrong one for a litigation hold is a quiet way to keep');
w('records far longer than any policy asked for.');
w();
w(`Delete attempt while held: **${tryDelete(withEvent, at('2028-01-01T00:00:00Z'))}**.`);
w(`Delete attempt after release, before retention: **${tryDelete(releasedEvent.object, at('2028-01-01T00:00:00Z'))}**.`);
w(`Delete attempt after both: **${tryDelete(releasedTemp.object, at('2028-01-01T00:00:00Z'))}**.`);
w();

// ---------------------------------------------------------------------------
w('## Status at a glance');
w();
w('| fixture | status at 2026-10-25T12:00:00Z | minutes remaining |');
w('|---|---|---:|');
const probe = at('2026-10-25T12:00:00Z');
for (const { fixture, decision } of decisions) {
  const remaining = minutesRemaining(decision, probe);
  w(`| ${fixture.id} | ${statusAt(decision, probe)} | ${remaining === null ? 'n/a' : remaining} |`);
}
w();

writeFileSync(join(RESULTS, 'report.md'), out.join('\n') + '\n');

const json = {
  label: 'Simulated result',
  generatedBy: 'scripts/report.ts',
  deterministic: true,
  tally: run.tally,
  sweep: run.sweepAt,
  packets: repro,
  maxScheduleHorizonMs: MAX_SCHEDULE_HORIZON_MS,
  deadlines: decisions.map(({ fixture, decision }) => ({
    id: fixture.id,
    covers: fixture.covers,
    basis: decision.basis,
    ruleVersion: decision.ruleVersion,
    calendarVersion: decision.calendarVersion,
    zoneTableVersion: decision.zoneTableVersion,
    deadline: render(decision.deadline),
    internalTarget: render(decision.internalTarget),
    trace: decision.trace,
  })),
};
writeFileSync(join(RESULTS, 'deadlines.json'), JSON.stringify(json, null, 2) + '\n');

console.log('wrote results/report.md and results/deadlines.json');
