// Runs every experiment and writes results/ as JSON plus a Markdown summary.
// The article quotes this file; it must never be edited by hand.
import { writeFileSync } from "node:fs";
import { CAPACITY_NOTE, EXPERIMENTS, envelope } from "../src/experiments.ts";

const rows: string[] = [];
const all: Record<string, unknown> = {};

rows.push("# Experiment results\n");
rows.push(`Generated by \`make report\`. Deterministic: seed 1234, ${CAPACITY_NOTE}.\n`);
rows.push("All figures are **simulated results** from a discrete-event model.");
rows.push("They are not measurements of any deployed Google Cloud service.\n");
rows.push("| Experiment | Mode | Arrived | Completed | Goodput/s | p50 ms | p95 ms | p99 ms | Abandoned | Rejected | Deferred | Expired |");
rows.push("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");

for (const exp of EXPERIMENTS) {
  const { open, bounded } = exp.run();
  all[exp.id] = { question: exp.question, open, bounded };
  for (const r of [open, bounded]) {
    const mode = r.label.split(" / ")[1] ?? r.label;
    rows.push(
      `| ${exp.id} | ${mode} | ${r.arrived} | ${r.completed} | ${r.goodputPerSec} |` +
        ` ${r.latency.p50} | ${r.latency.p95} | ${r.latency.p99} |` +
        ` ${r.abandoned} | ${r.rejected} | ${r.deferred} | ${r.expired} |`,
    );
  }
  writeFileSync(`results/${exp.id}.json`, JSON.stringify({ question: exp.question, open, bounded }, null, 2));
}

rows.push("\n## Overload envelope\n");
rows.push("Contention model ON. The coefficient is an assumption (ADR-002), not a measurement.\n");
for (const coeff of [0, 0.05]) {
  rows.push(`\n**contentionPerUnit = ${coeff}**\n`);
  rows.push("| Worker slots | Offered | Goodput/s | p99 ms |");
  rows.push("|---:|---:|---:|---:|");
  const pts = envelope(coeff);
  all[`envelope-${coeff}`] = pts;
  for (const p of pts) {
    rows.push(`| ${p.slots} | ${p.offeredMultiple}x | ${p.goodputPerSec} | ${p.p99Ms} |`);
  }
}

writeFileSync("results/experiments.json", JSON.stringify(all, null, 2));
writeFileSync("results/experiments.md", rows.join("\n") + "\n");
console.log(rows.join("\n"));
